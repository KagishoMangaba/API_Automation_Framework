package org.kagisho.models;

public class Accuracy {

    private int accuracy;

    public int getAccuracy() {
        return accuracy;
    }

    public void setAccuracy(int accuracy) {
        this.accuracy = accuracy;



    }

    @Override
    public String toString() {
        return "Accuracy{" +
                "accuracy=" + accuracy +
                '}';
    }
}
